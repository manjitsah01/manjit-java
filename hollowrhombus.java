import java.util.Scanner;

public class hollowrhombus {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        int  n = sc.nextInt();
        for(int i =1; i <=n; i++){
            // spaces 
            for(int j = 1 ; j<=n-i; j++){
if (i==1 || j==1|| i ==n || j==5 ) {                //peening 
                System.out.print("*");
            } else {
                System.out.print(" ");
            }
            // stars 
            

        
        System.out.println();
}
    }
}
    }
